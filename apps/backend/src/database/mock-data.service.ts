  getChartData(code: string) {
    const today = new Date();
    const basePrice: Record<string, number> = {
      BBCA: 9200, TLKM: 3150, BMRI: 5600, ASII: 4800, GOTO: 63,
    };
    const base = basePrice[code] ?? 1000;
    const data: { date: string; open: number; high: number; low: number; close: number; volume: number }[] = [];

    for (let i = 89; i >= 0; i--) {
      const d = new Date(today);
      d.setDate(d.getDate() - i);
      if (d.getDay() === 0 || d.getDay() === 6) continue;

      const noise = (Math.random() - 0.48) * base * 0.025;
      const open  = parseFloat((base + noise).toFixed(0));
      const close = parseFloat((open * (1 + (Math.random() - 0.48) * 0.02)).toFixed(0));
      const high  = parseFloat((Math.max(open, close) * (1 + Math.random() * 0.01)).toFixed(0));
      const low   = parseFloat((Math.min(open, close) * (1 - Math.random() * 0.01)).toFixed(0));

      data.push({
        date:   d.toISOString().split('T')[0],
        open, high, low, close,
        volume: Math.floor(100000 + Math.random() * 500000),
      });
    }
    return data;
  }
